test('default QR settles a table in one click and opens a cashier receipt', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('员工名称').fill('browser-owner');
  await page.getByLabel('PIN 码').fill('928461');
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await expect(page.getByRole('heading', { name: '选择桌台' })).toBeVisible();
  await expect(page.locator('.table-card')).toHaveCount(20);
  await page.getByRole('button', { name: /^T20/ }).click();
  await page.getByRole('button', { name: /^云吞面/ }).click();
  await page.getByRole('button', { name: '加入草稿 · RM 8.00' }).click();
  await page.getByRole('button', { name: '确认下单 / 送档口' }).click();
  await expect(page.getByRole('heading', { name: '选择桌台' })).toBeVisible();
  await page.getByRole('button', { name: /^T20/ }).click();
  await page.getByRole('button', { name: '查看账单 / 收款' }).click();
  await expect(page.getByRole('button', { name: '二维码', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('checkbox', { name: /人工核实/ })).toHaveCount(0);
  await page.getByRole('button', { name: '确认收款并清台' }).click();
  await expect(page.getByRole('heading', { name: '付款收据', exact: true })).toBeVisible();
  const paymentId = page.url().split('/').pop();
  const token = await page.evaluate(() => sessionStorage.getItem('koko-token'));
  const headers = { Authorization: `Bearer ${token}` };
  const before = await (await page.request.get(`/api/payments/${paymentId}/receipt`, { headers })).json();
  expect(before.method).toBe('QR');
  expect(before.total).toBe(800);
  expect(before.print_history).toHaveLength(1);
  expect(before.print_job.routing_group).toBe('RECEIPT');
  await page.reload();
  await expect(page.getByRole('heading', { name: '付款收据', exact: true })).toBeVisible();
  const after = await (await page.request.get(`/api/payments/${paymentId}/receipt`, { headers })).json();
  expect(after.print_history).toHaveLength(1);
  expect(after.print_job.id).toBe(before.print_job.id);
  await page.getByRole('link', { name: '← 返回桌台', exact: true }).click();
  await expect(page.getByRole('button', { name: /^T20/ })).toContainText('空桌');
});
